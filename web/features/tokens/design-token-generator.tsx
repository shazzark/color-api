"use client";

import {
  createColorObject,
  createCssVariablesBlock,
  createTailwindColorData,
  createToken,
  serializeDesignTokens,
  serializeJavaScriptObject,
  serializeScssVariables,
  serializeTypeScriptObject,
  validateTokenName,
  type ColorValue
} from "chromaforge";
import { useRef, useState, type FormEvent } from "react";
import { ColorInput } from "@/features/shared/color-input";
import { CopyButton, ColorResultList, ToolFeedback, ToolHeading } from "@/features/shared/color-results";
import { FormActions, SelectField, SubmitButton, TextField } from "@/features/shared/tool-controls";

type TokenDraft = { id: string; name: string; color?: ColorValue };
type OutputFormat = "json" | "css" | "javascript" | "typescript" | "scss" | "tailwind";

const initialColor: ColorValue = { format: "hex", value: "#3456d1" };
const outputOptions = [
  { value: "json", label: "Design Tokens JSON · schema v1" },
  { value: "css", label: "CSS custom properties" },
  { value: "javascript", label: "JavaScript object module" },
  { value: "typescript", label: "TypeScript object module" },
  { value: "scss", label: "SCSS variables" },
  { value: "tailwind", label: "Tailwind theme JSON data" }
] as const;
const fileExtensions: Record<OutputFormat, string> = {
  json: "tokens.json",
  css: "css",
  javascript: "js",
  typescript: "ts",
  scss: "scss",
  tailwind: "tailwind.json"
};

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : "The package could not serialize these design tokens.";
}

export function DesignTokenGenerator() {
  const [tokens, setTokens] = useState<TokenDraft[]>([{ id: "token-0", name: "brand", color: initialColor }]);
  const [format, setFormat] = useState<OutputFormat>("json");
  const [output, setOutput] = useState("");
  const [error, setError] = useState("");
  const [feedback, setFeedback] = useState("");
  const [resetKey, setResetKey] = useState(0);
  const nextId = useRef(1);

  function updateToken(id: string, changes: Partial<TokenDraft>) {
    setTokens((current) => current.map((token) => token.id === id ? { ...token, ...changes } : token));
    setOutput("");
    setError("");
    setFeedback("");
  }

  function addToken() {
    setTokens((current) => [...current, { id: `token-${nextId.current++}`, name: "", color: initialColor }]);
    setOutput("");
    setError("");
    setFeedback("");
  }

  function removeToken(id: string) {
    setTokens((current) => current.filter((token) => token.id !== id));
    setOutput("");
    setError("");
    setFeedback("");
  }

  function serialize(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setOutput("");
    setFeedback("");
    try {
      const seenNames = new Set<string>();
      const normalizedEntries = tokens.map((draft) => {
        if (!draft.color) throw new Error(`Enter a valid color for token “${draft.name || "(unnamed)"}”.`);
        const name = validateTokenName(draft.name);
        if (seenNames.has(name)) throw new Error(`Token name “${name}” is duplicated.`);
        seenNames.add(name);
        const token = createToken(name, draft.color);
        return { name: token.name, color: token.color };
      });
      const colorMap = createColorObject(Object.fromEntries(normalizedEntries.map(({ name, color }) => [name, color])));
      const serialized = format === "json"
        ? serializeDesignTokens(colorMap)
        : format === "css"
          ? createCssVariablesBlock(colorMap)
          : format === "javascript"
            ? serializeJavaScriptObject(colorMap)
            : format === "typescript"
              ? serializeTypeScriptObject(colorMap)
              : format === "scss"
                ? serializeScssVariables(colorMap)
                : JSON.stringify(createTailwindColorData(colorMap), null, 2);
      setOutput(serialized);
      setError("");
      setFeedback("Design tokens generated by chromaforge@1.0.1.");
    } catch (caught) {
      setError(errorMessage(caught));
    }
  }

  function download() {
    if (!output) return;
    try {
      const blob = new Blob([output], { type: "text/plain;charset=utf-8" });
      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = url;
      link.download = `chromaforge-design-tokens.${fileExtensions[format]}`;
      document.body.append(link);
      link.click();
      setFeedback(`Downloaded ${link.download}.`);
      link.remove();
      window.setTimeout(() => URL.revokeObjectURL(url), 1000);
      setError("");
    } catch {
      setError("The browser could not prepare this download. Copy the generated output instead.");
      setFeedback("");
    }
  }

  function reset() {
    setTokens([{ id: `token-reset-${resetKey + 1}`, name: "brand", color: initialColor }]);
    setResetKey((value) => value + 1);
    nextId.current = 1;
    setFormat("json");
    setOutput("");
    setError("");
    setFeedback("");
  }

  const previewItems = tokens
    .filter((token): token is TokenDraft & { color: ColorValue } => token.color !== undefined)
    .map((token) => ({ label: token.name || "Unnamed token", color: token.color }));

  return (
    <section className="color-tool" aria-labelledby="tokens-title">
      <ToolHeading
        id="tokens-title"
        eyebrow="PACKAGE TOOL · LOCAL SERIALIZATION"
        title="Design token generator"
        description="Name colors and serialize them into ChromaForge’s supported formats. Names and color values are validated by the published package; nothing is uploaded or saved to an account."
      />
      <div className="color-tool__grid">
        <form className="tool-panel" noValidate onSubmit={serialize}>
          <h2>Named colors</h2>
          {tokens.map((token, index) => (
            <fieldset className="token-entry" key={`${resetKey}-${token.id}`}>
              <legend>Token {index + 1}</legend>
              <TextField
                id={`token-name-${token.id}`}
                label="Token name"
                value={token.name}
                onChange={(name) => updateToken(token.id, { name })}
                hint="Lowercase letter first; then lowercase letters, numbers, or hyphens."
              />
              <ColorInput
                id={`token-color-${token.id}`}
                label={`Color for ${token.name || `token ${index + 1}`}`}
                initialColor={token.color ?? initialColor}
                onChange={(color) => updateToken(token.id, { color })}
              />
              <button className="tool-button tool-button--quiet" type="button" disabled={tokens.length === 1} onClick={() => removeToken(token.id)} aria-label={`Remove token ${token.name || index + 1}`}>Remove token</button>
            </fieldset>
          ))}
          <SelectField
            id="token-output-format"
            label="Export format"
            value={format}
            options={outputOptions}
            onChange={(value) => { const selected = outputOptions.find((option) => option.value === value); if (selected) { setFormat(selected.value); setOutput(""); setFeedback(""); } }}
          />
          <FormActions>
            <button className="tool-button tool-button--quiet" type="button" onClick={addToken}>Add color token</button>
            <SubmitButton>Generate tokens</SubmitButton>
            <button className="tool-button tool-button--quiet" type="button" onClick={reset}>Reset</button>
          </FormActions>
          <ToolFeedback message={error} error />
          <ToolFeedback message={feedback} />
        </form>

        <div className="token-output-column">
          <section className="tool-panel" aria-labelledby="token-preview-title">
            <h2 id="token-preview-title">Color preview</h2>
            <ColorResultList items={previewItems} emptyMessage="Add a valid color to preview token values." />
          </section>
          <section className="tool-panel" aria-labelledby="token-output-title">
            <h2 id="token-output-title">Serialized output</h2>
            {output ? (
              <>
                <pre className="token-output"><code>{output}</code></pre>
                <div className="tool-actions">
                  <CopyButton value={output} label="generated design tokens" />
                  <button className="tool-button tool-button--quiet" type="button" onClick={download}>Download file</button>
                </div>
              </>
            ) : <p className="tool-empty" role="status">Choose colors and an export format, then generate tokens.</p>}
            <p className="tool-inline-note">Supported formats: versioned design-token JSON, CSS variables, JavaScript, TypeScript, SCSS, and Tailwind theme data. Token names follow the package rule: <code>^[a-z][a-z0-9-]*$</code>.</p>
          </section>
        </div>
      </div>
    </section>
  );
}
